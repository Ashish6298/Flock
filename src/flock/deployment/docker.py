# Deterministic YAML Serialization
# ------------------------------------------------------------------

def to_yaml(data: Dict[str, Any] | List[Any] | str | int | float | bool, indent: int = 0) -> str:
    """Format inputs dictionary into sorted, deterministic YAML string."""
    lines: List[str] = []
    if isinstance(data, dict):
        for k in sorted(data.keys()):
            v = data[k]
            if v is None:
                continue
            if isinstance(v, (dict, list)):
                lines.append(f"{' ' * indent}{k}:")
                sub = to_yaml(v, indent + 2)
                if sub:
                    lines.append(sub)
            else:
                if isinstance(v, bool):
                    v_str = "true" if v else "false"
                else:
                    v_str = str(v)
                lines.append(f"{' ' * indent}{k}: {v_str}")
    elif isinstance(data, list):
        for item in data:
            if isinstance(item, (dict, list)):
                item_lines = to_yaml(item, indent + 2).split("\n")
                if item_lines:
                    first_line = item_lines[0].lstrip()
                    lines.append(f"{' ' * indent}- {first_line}")
                    for extra in item_lines[1:]:
                        lines.append(extra)
            else:
                lines.append(f"{' ' * indent}- {item}")
    return "\n".join(lines)


class ComposeEngine:
    """Orchestration compiler generating deterministic docker-compose YAMLs."""

    def generate_compose(self, project: ComposeProject) -> str:
        """Serialize ComposeProject model into clean YAML format."""
        return to_yaml(project.model_dump())

    def generate_cluster_compose(
        self,
        cluster_name: str,
        replicas: int = 3,
        image: str = "flock-node:latest",
        ports_start: int = 8080,
    ) -> ComposeProject:
        """Build ready-to-run multi-node ComposeProject specifications."""
        services: Dict[str, ComposeService] = {}
        networks = {"flock-mesh": ComposeNetwork()}
        volumes = {"flock-data": ComposeVolume()}

        # Coordinator
        coord_name = f"{cluster_name}-coordinator"
        services[coord_name] = ComposeService(
            container_name=coord_name,
            image=image,
            ports=[f"{ports_start}:{ports_start}"],
            volumes=["flock-data:/var/flock"],
            networks=["flock-mesh"],
            environment={"FLOCK_ROLE": "coordinator", "FLOCK_NODE_ID": coord_name},
            restart="always",
        )

        # Workers
        for i in range(1, replicas):
            worker_name = f"{cluster_name}-worker-{i}"
            services[worker_name] = ComposeService(
                container_name=worker_name,
                image=image,
                ports=[f"{ports_start + i}:{ports_start + i}"],
                volumes=["flock-data:/var/flock"],
                networks=["flock-mesh"],
                environment={"FLOCK_ROLE": "worker", "FLOCK_NODE_ID": worker_name},
                depends_on={coord_name: ComposeDependsOn(condition="service_started")},
                restart="always",
            )

        return ComposeProject(services=services, networks=networks, volumes=volumes)


class ComposeValidationResult(BaseModel):
    """Validation report mapping service inconsistencies."""
    is_valid: bool
    errors: List[str] = Field(default_factory=list)

    model_config = {"frozen": True}


class ComposeValidator:
    """Compose specifications structural validator."""

    @staticmethod
    def validate_project(project: ComposeProject) -> ComposeValidationResult:
        """Assert unique service names, valid dependency references, and port format syntax."""
        errors: List[str] = []
        services = project.services

        for name, service in services.items():
            # 1. Dependency checks
            for dep_name in service.depends_on.keys():
                if dep_name not in services:
                    errors.append(f"Service '{name}' depends on missing service '{dep_name}'")

            # 2. Port mapping check
            for p in service.ports:
                if ":" not in p:
                    errors.append(f"Invalid port mapping: '{p}' in service '{name}'")

        return ComposeValidationResult(
            is_valid=len(errors) == 0,
            errors=errors
        )
