class DockerfileGenerator:
    """Generates Dockerfiles deterministically from container specifications."""

    def generate_dockerfile(
        self,
        base_image: str = "python:3.11-slim",
        working_dir: str = "/app",
        requirements_path: Optional[str] = "requirements.txt",
        entrypoint: Optional[List[str]] = None,
        cmd: Optional[List[str]] = None,
        env_vars: Optional[Dict[str, str]] = None,
        ports: Optional[List[int]] = None,
        healthcheck: Optional[DockerHealthCheck] = None,
        labels: Optional[Dict[str, str]] = None,
    ) -> str:
        """Create deterministic Dockerfile content string."""
        lines = []
        lines.append(f"# Generated by Flock Docker Generator — 2026-07-26")
        lines.append(f"FROM {base_image}\n")
        lines.append(f"WORKDIR {working_dir}\n")

        if env_vars:
            for k, v in sorted(env_vars.items()):
                lines.append(f"ENV {k}={v}")
            lines.append("")

        if labels:
            for k, v in sorted(labels.items()):
                lines.append(f"LABEL {k}={v}")
            lines.append("")

        lines.append("# Copy requirements and install dependencies")
        if requirements_path:
            lines.append(f"COPY {requirements_path} .")
            lines.append("RUN pip install --no-cache-dir -r requirements.txt\n")

        lines.append("COPY . .\n")

        if ports:
            for p in sorted(ports):
                lines.append(f"EXPOSE {p}")
            lines.append("")

        if healthcheck and healthcheck.test_command:
            test_str = " ".join(healthcheck.test_command)
            lines.append(
                f"HEALTHCHECK --interval={healthcheck.interval}s --timeout={healthcheck.timeout}s --retries={healthcheck.retries} \\"
            )
            lines.append(f"  CMD {test_str}\n")

        if entrypoint:
            entry_str = ", ".join(f'"{x}"' for x in entrypoint)
            lines.append(f"ENTRYPOINT [{entry_str}]")

        if cmd:
            cmd_str = ", ".join(f'"{x}"' for x in cmd)
            lines.append(f"CMD [{cmd_str}]")

        return "\n".join(lines)


class DockerValidationResult(BaseModel):
    """Validation report mapping errors."""
    is_valid: bool
    errors: List[str] = Field(default_factory=list)

    model_config = {"frozen": True}


class DockerValidator:
    """Docker configurations constraint validator."""

    @staticmethod
    def validate_container(container: DockerContainer) -> DockerValidationResult:
        """Validate images name format, port ranges, and duplicate mounts."""
        errors = []
        
        # 1. Image name validation
        img = container.image.image_name
        if not img or len(img) < 2:
            errors.append(f"Invalid image name: '{img}'")

        # 2. Port range validation
        for net in container.networks:
            for host_port, container_port in net.published_ports.items():
                if host_port < 1 or host_port > 65535 or container_port < 1 or container_port > 65535:
                    errors.append(f"Invalid port mapping: {host_port}:{container_port}")

        # 3. Duplicate mount validation
        mounts = set()
        for vol in container.volumes:
            if vol.target in mounts:
                errors.append(f"Duplicate mount target detected: '{vol.target}'")
            mounts.add(vol.target)

        # 4. Memory limit validation
        cfg = container.runtime_config
        if cfg.memory_limit_mb and cfg.memory_reservation_mb:
            if cfg.memory_reservation_mb > cfg.memory_limit_mb:
                errors.append("Memory reservation cannot exceed memory limit.")

        return DockerValidationResult(
            is_valid=len(errors) == 0,
            errors=errors
        )


